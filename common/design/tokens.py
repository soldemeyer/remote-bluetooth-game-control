"""The product's design tokens, in one place.

**These were already the product's colours -- they simply had no name and no
home.** `#4c8dff`, `#3ecf8e`, `#f5a623`, `#ff5c5c` and `#1a1d26` each appeared
as a literal in two or three of `client/gui/app.py`,
`client/gui/latency_plot.py` and `server/web/static/style.css`, with nothing
tying them together. Six of the eight core colours were duplicated. So this
module extracts and names what existed rather than inventing a new palette,
which is also why the redesign does not look like a different product.

Two consumers, one source:

* **Qt** imports this directly and builds a stylesheet from it.
* **The web** gets `server/web/static/tokens.css`, generated by
  `tools/build_design_tokens.py` and committed, with a test that regenerates
  and compares -- the same arrangement `build_controller_art.py`,
  `build_controller_presets.py` and `build_icon.py` already use.

Colour syntax differs between the two and the difference is easy to get wrong:
CSS wants a 0..1 float alpha, Qt's stylesheet wants a percentage. Each
:class:`Color` renders both rather than leaving callers to remember.
"""

from __future__ import annotations

from dataclasses import dataclass

__all__ = ["Color", "Motion", "Radius", "Space", "Type", "palette"]


@dataclass(frozen=True, slots=True)
class Color:
    """One colour, renderable for CSS or for a Qt stylesheet."""

    r: int
    g: int
    b: int
    a: float = 1.0

    @classmethod
    def hex(cls, value: str, a: float = 1.0) -> Color:
        text = value.lstrip("#")
        if len(text) != 6:
            raise ValueError(f"expected a 6-digit hex colour, got {value!r}")
        return cls(int(text[0:2], 16), int(text[2:4], 16), int(text[4:6], 16), a)

    def alpha(self, a: float) -> Color:
        """The same colour at a different opacity."""
        return Color(self.r, self.g, self.b, a)

    def over(self, backdrop: Color) -> Color:
        """This colour composited onto ``backdrop``, fully opaque.

        Qt cannot blur what is behind a widget, so a "glass" surface there is a
        translucent fill over a *known* background. Where the background is
        known, resolving the composite up front is both cheaper and more
        predictable than asking the toolkit to blend at paint time.
        """
        if self.a >= 1.0:
            return self
        blend = lambda top, bottom: round(top * self.a + bottom * (1 - self.a))
        return Color(
            blend(self.r, backdrop.r), blend(self.g, backdrop.g), blend(self.b, backdrop.b)
        )

    @property
    def css(self) -> str:
        """CSS form. Alpha is a 0..1 float, which is what CSS expects."""
        if self.a >= 1.0:
            return f"#{self.r:02X}{self.g:02X}{self.b:02X}"
        return f"rgba({self.r}, {self.g}, {self.b}, {self.a:g})"

    @property
    def qss(self) -> str:
        """Qt stylesheet form. Alpha is a **percentage**, not a float.

        Qt accepts `rgba(r, g, b, 40%)`; handing it a 0..1 float is read as an
        almost totally transparent colour, which renders as "the style did not
        apply" rather than as an error.
        """
        if self.a >= 1.0:
            return f"#{self.r:02X}{self.g:02X}{self.b:02X}"
        return f"rgba({self.r}, {self.g}, {self.b}, {self.a * 100:g}%)"


