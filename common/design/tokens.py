class Space:
    """Spacing scale. Every margin and gap comes from here."""

    XS = 4
    SM = 8
    MD = 12
    LG = 16
    XL = 24
    XXL = 32
    XXXL = 48

    ALL = (XS, SM, MD, LG, XL, XXL, XXXL)


class Radius:
    """Corner radii, by the size of the thing being rounded.

    Not everything is maximally rounded: a 6 px control beside an 18 px panel
    is what reads as "designed", where one radius everywhere reads as a theme
    applied in bulk.
    """

    CONTROL = 8      # buttons, inputs, small chips
    CARD = 12        # cards, list rows, metric tiles
    PANEL = 16       # glass panels, drawers, side rails
    DIALOG = 20      # modal surfaces
    PILL = 999       # fully rounded: badges, toggles


class Type:
    """Type scale in points/px, plus the family stack.

    System fonts only. The project ships no font and should not start: a font
    file is another thing for the PyInstaller and AppImage bundles to carry
    and another way for them to fail on someone else's machine.
    """

    FAMILY = '"Segoe UI", -apple-system, BlinkMacSystemFont, Roboto, "Helvetica Neue", sans-serif'
    FAMILY_MONO = '"Cascadia Mono", ui-monospace, "SF Mono", Menlo, Consolas, monospace'

    #: The same stacks as a list, for `QFont.setFamilies`. Qt wants the
    #: fallbacks as separate entries rather than one CSS string, and silently
    #: falls back to a default if handed the string form.
    FAMILIES = ("Segoe UI", "Inter", "Roboto", "Helvetica Neue", "Sans Serif")
    FAMILIES_MONO = ("Cascadia Mono", "Consolas", "SF Mono", "Menlo", "Monospace")

    DISPLAY = 24     # window/page title
    TITLE = 19       # section heading
    HEADING = 16     # card title
    BODY = 15        # default
    LABEL = 13       # form labels, secondary text
    META = 12        # metadata, units, tooltips

    WEIGHT_REGULAR = 400
    WEIGHT_MEDIUM = 500
    WEIGHT_SEMIBOLD = 600

    #: Metrics update several times a second. Proportional digits change width
    #: as the value changes, so the number jitters sideways while you read it.
    NUMERIC_FEATURE = "tnum"


class Motion:
    """Durations in milliseconds.

    Short on purpose. A control that animates for longer than about 150 ms
    feels like it is lagging behind the click rather than responding to it,
    and this is a product whose entire premise is responsiveness.

    Only ``transform`` and ``opacity`` should be animated. Animating geometry,
    colour of large areas, or anything continuous costs a repaint per frame --
    in the client that repaint competes with the decoder for the GIL, which was
    measured to matter (see LATENCY_OPTIMIZATION.md).
    """

    INSTANT = 90     # press feedback
    FAST = 120       # hover, focus
    NORMAL = 180     # panels, drawers, tooltips
    SLOW = 240       # view changes
    EASE = "cubic-bezier(0.2, 0.0, 0.2, 1)"


def resolved_glass(name: str = "surface-glass", *, on: str = "background-base") -> Color:
    """A glass token flattened onto a backdrop.

    For Qt, and for anywhere a translucent fill would otherwise composite over
    something unknown. See :meth:`Color.over`.
    """
    return palette[name].over(palette[on])
